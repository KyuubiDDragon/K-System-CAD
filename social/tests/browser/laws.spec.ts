import {test,expect} from '@playwright/test';
import {execFileSync} from 'node:child_process';
import {resolve} from 'node:path';
test('laws: CAD publisher interface, safe text, public history and mobile reading',async({page,context,baseURL})=>{
 const token=execFileSync('docker-compose',['-f','backend/social/tests/compose.yml','exec','-T','backend','cat','/tmp/laws-test-session'],{cwd:resolve(process.cwd(),'..'),encoding:'utf8'}).trim();
 await context.addCookies([{name:'auth_token',value:token,url:baseURL!}]);
 await page.goto('/#/laws');
 await expect(page.getByRole('heading',{name:'Gesetze',exact:true})).toBeVisible();
 await page.getByText('Community-Verwaltung',{exact:true}).click();
 await page.getByRole('button',{name:'Straßenverkehrsordnung',exact:true}).click();
 await expect(page.getByLabel('Titel',{exact:true})).toHaveValue('Straßenverkehrsordnung');
 await page.getByLabel('Titel',{exact:true}).fill('Straßenverkehr');
 await page.getByLabel('Beschreibung',{exact:true}).fill('Regeln für die Straßen');
 await page.getByRole('button',{name:'Gesetzbuch anlegen',exact:true}).click();
 await page.getByRole('button',{name:'Paragraph anlegen'}).click();
 await page.getByLabel('Paragraphennummer',{exact:true}).fill('12');
 await page.locator('.law-editor').getByLabel('Titel',{exact:true}).fill('Vorfahrt');
 await page.getByLabel('Gesetzestext').fill('Sicher fahren. <script>alert(1)</script>');
 await page.locator('.law-editor').getByLabel('Begründung').fill('Neue Vorschrift');
 await page.getByRole('button',{name:'Entwurf speichern',exact:true}).click();
 await expect(page.getByText('Entwurf · nicht veröffentlicht')).toBeVisible();
 await page.getByRole('button',{name:'Diese Fassung veröffentlichen'}).click();
 await expect(page.getByText('Geltende Fassung',{exact:true})).toBeVisible();
 const link=await page.getByRole('link',{name:'Direktlink'}).getAttribute('href');
 await context.clearCookies();
 await page.goto(link!);
 await page.reload();
 await expect(page.getByRole('heading',{name:'§ 12 · Vorfahrt'})).toBeVisible();
 await expect(page.getByRole('button',{name:'Änderung entwerfen'})).toHaveCount(0);
 await expect(page.locator('.law-text').first()).toContainText('<script>alert(1)</script>');
 await page.getByLabel('Alle Gesetzbücher durchsuchen').fill('Vorfahrt');
 await page.getByRole('button',{name:'Suchen',exact:true}).click();
 await expect(page.getByRole('heading',{name:'1 Treffer'})).toBeVisible();
 await page.locator('.law-result').click();
 await expect(page.getByRole('heading',{name:'§ 12 · Vorfahrt'})).toBeVisible();
 await page.setViewportSize({width:390,height:844});
 await expect.poll(()=>page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBeTruthy();
 await page.screenshot({path:'test-results/laws-mobile.png',fullPage:true});
});
